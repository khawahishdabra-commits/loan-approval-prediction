import streamlit as st
import pandas as pd
import joblib


# --------------------------------------------------
# Load trained model
# --------------------------------------------------

model = joblib.load("loan_approval_model.pkl")


# --------------------------------------------------
# Page configuration
# --------------------------------------------------

st.set_page_config(
    page_title="Loan Approval Predictor",
    page_icon="🏦",
    layout="centered"
)


# --------------------------------------------------
# Header
# --------------------------------------------------

st.title("🏦 Loan Approval Predictor")

st.write(
    "Enter the applicant's information below to estimate "
    "the probability of loan approval."
)

st.divider()


# --------------------------------------------------
# Applicant Information
# --------------------------------------------------

st.subheader("👤 Applicant Information")

col1, col2 = st.columns(2)

with col1:
    gender = st.selectbox(
        "Gender",
        ["Male", "Female"]
    )

    married = st.selectbox(
        "Married",
        ["Yes", "No"]
    )

    dependents = st.selectbox(
        "Dependents",
        ["0", "1", "2", "3+"]
    )

    education = st.selectbox(
        "Education",
        ["Graduate", "Not Graduate"]
    )

    self_employed = st.selectbox(
        "Self Employed",
        ["No", "Yes"]
    )

with col2:
    applicant_income = st.number_input(
        "Applicant Income",
        min_value=0,
        value=5000,
        step=100
    )

    coapplicant_income = st.number_input(
        "Coapplicant Income",
        min_value=0,
        value=1500,
        step=100
    )

    loan_amount = st.number_input(
        "Loan Amount",
        min_value=0,
        value=120,
        step=10
    )

    loan_amount_term = st.selectbox(
        "Loan Amount Term",
        [12, 36, 60, 84, 120, 180, 240, 300, 360, 480],
        index=8
    )

    credit_history = st.selectbox(
        "Credit History",
        [1.0, 0.0],
        format_func=lambda x: "Good (1)" if x == 1.0 else "Poor (0)"
    )

property_area = st.selectbox(
    "Property Area",
    ["Urban", "Semiurban", "Rural"]
)


st.divider()


# --------------------------------------------------
# Prediction
# --------------------------------------------------

if st.button(
    "🔍 Predict Loan Approval",
    use_container_width=True
):

    new_applicant = pd.DataFrame([{
        "Gender": gender,
        "Married": married,
        "Dependents": dependents,
        "Education": education,
        "Self_Employed": self_employed,
        "ApplicantIncome": applicant_income,
        "CoapplicantIncome": coapplicant_income,
        "LoanAmount": loan_amount,
        "Loan_Amount_Term": loan_amount_term,
        "Credit_History": credit_history,
        "Property_Area": property_area
    }])

    prediction = model.predict(new_applicant)[0]

    probabilities = model.predict_proba(new_applicant)[0]

    rejection_probability = probabilities[0]
    approval_probability = probabilities[1]


    # --------------------------------------------------
    # Result
    # --------------------------------------------------

    st.subheader("📊 Prediction Result")

    if prediction == "Y":

        st.success("✅ Loan Approved")

        st.metric(
            "Approval Probability",
            f"{approval_probability * 100:.2f}%"
        )

    else:

        st.error("❌ Loan Rejected")

        st.metric(
            "Approval Probability",
            f"{approval_probability * 100:.2f}%"
        )


    # Probability details

    col1, col2 = st.columns(2)

    with col1:
        st.write(
            f"**Approval:** {approval_probability * 100:.2f}%"
        )

    with col2:
        st.write(
            f"**Rejection:** {rejection_probability * 100:.2f}%"
        )


    st.progress(float(approval_probability))


    # --------------------------------------------------
    # Disclaimer
    # --------------------------------------------------

    st.caption(
        "This prediction is generated by a machine learning model "
        "and should not be treated as a guaranteed lending decision."
    )